CREATE DATABASE IF NOT EXISTS shop
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE shop;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS product_images, reviews, order_items, orders, cards, cart_items, sessions, products, users;
SET FOREIGN_KEY_CHECKS = 1;

-- 회원 — membership_until 이 오늘 이후면 쫑클럽 회원
CREATE TABLE users (
  id               INT AUTO_INCREMENT PRIMARY KEY,
  email            VARCHAR(100) NOT NULL UNIQUE,
  name             VARCHAR(50)  NOT NULL,
  password_hash    VARCHAR(255) NOT NULL,
  phone            VARCHAR(20)  NOT NULL DEFAULT '',
  address          VARCHAR(200) NOT NULL DEFAULT '',
  membership_until DATE NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- PHP 세션 — WEB1/WEB2가 같은 세션을 보도록 DB에 저장 (VIP 전환 후에도 로그인 유지)
CREATE TABLE sessions (
  id         VARCHAR(128) PRIMARY KEY,
  data       MEDIUMTEXT NOT NULL,
  updated_at INT NOT NULL
);

-- 상품 — 판매가 = price × (100 - discount) / 100
CREATE TABLE products (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  seller_id   INT NULL,
  seller      VARCHAR(50)  NOT NULL DEFAULT '쫑마켓',
  name        VARCHAR(100) NOT NULL,
  category    VARCHAR(20)  NOT NULL,
  icon        VARCHAR(16)  NOT NULL DEFAULT '📦',
  price       INT NOT NULL,
  discount    INT NOT NULL DEFAULT 0,
  stock       INT NOT NULL DEFAULT 0,
  delivery    VARCHAR(10)  NOT NULL DEFAULT '일반배송',   -- 쫑배송 / 무료배송 / 일반배송
  rating      DECIMAL(2,1) NOT NULL DEFAULT 0.0,
  reviews     INT NOT NULL DEFAULT 0,
  description TEXT NOT NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_category (category),
  FOREIGN KEY (seller_id) REFERENCES users(id) ON DELETE SET NULL
);

-- 상품 사진 — 판매자가 올린 사진을 DB에 저장 (WEB1/WEB2 어느 쪽에서 올려도 양쪽에서 보임)
--             사진이 없는 상품은 img.php 가 카테고리 색으로 기본 이미지를 그려 준다
CREATE TABLE product_images (
  product_id INT PRIMARY KEY,
  mime       VARCHAR(20) NOT NULL,
  data       MEDIUMBLOB NOT NULL,
  updated_at DATETIME NOT NULL,
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE TABLE cart_items (
  user_id    INT NOT NULL,
  product_id INT NOT NULL,
  qty        INT NOT NULL DEFAULT 1,
  PRIMARY KEY (user_id, product_id),
  FOREIGN KEY (user_id)    REFERENCES users(id)    ON DELETE CASCADE,
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

-- 결제 카드 — 카드번호 전체와 CVC는 저장하지 않는다 (끝 4자리만)
CREATE TABLE cards (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  user_id    INT NOT NULL,
  brand      VARCHAR(20) NOT NULL,
  last4      CHAR(4)     NOT NULL,
  holder     VARCHAR(50) NOT NULL,
  exp_month  INT NOT NULL,
  exp_year   INT NOT NULL,
  is_default INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 주문 — 배송 단계는 주문 시각부터 지난 시간으로 계산 (가상 배송)
--        status 는 '진행' / '주문취소' / '구매확정'
CREATE TABLE orders (
  id           INT AUTO_INCREMENT PRIMARY KEY,
  user_id      INT NOT NULL,
  recipient    VARCHAR(50)  NOT NULL,
  phone        VARCHAR(20)  NOT NULL,
  address      VARCHAR(200) NOT NULL,
  memo         VARCHAR(100) NOT NULL DEFAULT '',
  pay_method   VARCHAR(20)  NOT NULL,        -- 카드 / 계좌이체 / 휴대폰
  pay_label    VARCHAR(60)  NOT NULL,        -- 예) VISA ****1111
  tracking_no  VARCHAR(20)  NOT NULL,
  items_total  INT NOT NULL,
  member_dc    INT NOT NULL DEFAULT 0,
  shipping_fee INT NOT NULL DEFAULT 0,
  total        INT NOT NULL,
  status       VARCHAR(20) NOT NULL DEFAULT '진행',
  created_at   DATETIME NOT NULL,
  closed_at    DATETIME NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE order_items (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  order_id   INT NOT NULL,
  product_id INT NULL,
  name       VARCHAR(100) NOT NULL,
  icon       VARCHAR(16)  NOT NULL,
  price      INT NOT NULL,
  qty        INT NOT NULL,
  reviewed   INT NOT NULL DEFAULT 0,
  FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
);

-- 상품평 — user_id 가 NULL 이면 시드로 넣은 가상 리뷰
CREATE TABLE reviews (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  product_id INT NOT NULL,
  user_id    INT NULL,
  author     VARCHAR(20) NOT NULL,
  rating     INT NOT NULL,
  body       TEXT NOT NULL,
  option_txt VARCHAR(50) NOT NULL DEFAULT '',
  helpful    INT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL,
  INDEX idx_product (product_id),
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id)    REFERENCES users(id)    ON DELETE SET NULL
);

